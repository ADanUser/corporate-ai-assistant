"""
Ограничение частоты запросов (rate limiting).

Зачем: защита от случайного цикла, от скрипта-перебора и от подбора
формулировок в обход injection-детектора. Заодно ограничивает расходы
на LLM — каждый запрос стоит денег.

Как считаем: "скользящее окно". Для каждого пользователя храним времена
последних запросов, выбрасываем всё старше окна и смотрим, сколько
осталось. Хранение в памяти — для демо этого достаточно; в проде такое
живёт в Redis, чтобы лимит был общим для всех процессов сервиса.
"""

import time
from collections import defaultdict

# Сколько запросов разрешаем одному пользователю за окно
MAX_REQUESTS = 10
# Длина окна в секундах
WINDOW_SECONDS = 60

# user_id -> список моментов времени, когда приходили запросы
_history = defaultdict(list)


def check_rate_limit(user_id: str) -> bool:
    """
    Проверяет, не превышен ли лимит, и записывает текущий запрос.
    Возвращает True, если запрос разрешён, False — если лимит исчерпан.
    """
    now = time.time()
    window_start = now - WINDOW_SECONDS

    # Оставляем только запросы внутри окна, остальные забываем
    recent = [t for t in _history[user_id] if t > window_start]

    # Лимит исчерпан — текущий запрос НЕ записываем.
    # Иначе непрерывный поток запросов держал бы окно вечно полным,
    # и пользователь не смог бы разблокироваться никогда.
    if len(recent) >= MAX_REQUESTS:
        _history[user_id] = recent
        return False

    recent.append(now)
    _history[user_id] = recent
    return True