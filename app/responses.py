"""
Шаблоны ответов ассистента.
"""

# ── Типы ответов ──
# Каждый терминальный узел помечает свой ответ типом. Это нужно не
# пользователю, а нам: по answer_type удобно фильтровать журнал
# ("сколько было отказов по правам?") и проверять траекторию на этапе
# evaluation ("на denied-кейсе ответ обязан быть типа denied").
KNOWLEDGE = "knowledge"          # ответ по документу
NO_SOURCE = "no_source"          # не нашли ничего подходящего
DENIED = "denied"                # нет прав
BLOCKED = "blocked"              # заблокировано security
TOOL_DISABLED = "tool_disabled"  # инструмент выключен админом
ACTION_DONE = "action_done"      # действие выполнено после approve
ACTION_REJECTED = "action_rejected"  # действие отклонено человеком


def knowledge_answer(text: str, source: str) -> str:
    """
    Ответ по документу. Источник печатается прямо в тексте, а не только
    в отдельном поле: пользователь должен видеть, откуда взят ответ,
    даже если интерфейс поле sources не показывает.
    """
    return f"{text}\n\nИсточник: {source}"


def no_source_answer() -> str:
    """
    Честное "не найдено" + следующий шаг.
    """
    return (
        "В доступных мне документах нет ответа на этот вопрос.\n\n"
        "Что можно сделать дальше:\n"
        "— переформулировать вопрос конкретнее;\n"
        "— уточнить у владельца нужного документа, есть ли такое правило;\n"
        "— если документ существует, но мне недоступен — запросить доступ."
    )


def denied_answer(what: str) -> str:
    """
    Отказ по правам. Важно: не раскрываем, ЧТО именно скрыто.
    "У вас нет доступа к зарплатам" — это уже утечка: мы подтвердили,
    что такой документ существует. Говорим про право, а не про данные.
    """
    return (
        f"У вашей роли нет прав на это действие: {what}.\n\n"
        "Если доступ нужен для работы — запросите его у своего руководителя."
    )


def blocked_answer() -> str:
    """Запрос отклонён детектором инъекций."""
    return (
        "Запрос отклонён: он содержит признаки небезопасной инструкции.\n\n"
        "Если это обычный рабочий вопрос — задайте его другими словами."
    )


def tool_disabled_answer(action: str) -> str:
    """Инструмент временно выключен админом (kill switch)."""
    return (
        f"Действие «{action}» временно отключено администратором.\n\n"
        "Это временная мера, попробуйте позже или обратитесь к администратору."
    )


def action_done_answer(title: str, approver: str) -> str:
    """
    Подтверждённое действие.
    ЧТО было сделано и КЕМ подтверждено — иначе разбирать инцидент
    придётся по логам, а не по переписке.
    """
    return (
        f"Готово. Создана задача: «{title}».\n"
        f"Действие выполнено после подтверждения пользователем {approver}."
    )


def action_rejected_answer(title: str) -> str:
    """Отклонённое действие + что осталось от черновика."""
    return (
        f"Действие не выполнено: создание задачи отклонено.\n"
        f"Черновик сохранён в журнале: «{title}». "
        "Вы можете переформулировать задачу и предложить её снова."
    )